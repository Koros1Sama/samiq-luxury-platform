import fs from 'fs';
import path from 'path';
import sharp from 'sharp';

const outputDir = path.resolve(process.cwd(), 'public/media/products');
if (!fs.existsSync(outputDir)) {
  fs.mkdirSync(outputDir, { recursive: true });
}

const productNames = [
  'serum-vitamin-c.jpg',
  'cleanser-hydrating.jpg',
  'serum-niacinamide.jpg',
  'lipstick-couture.jpg',
  'eyeshadow-palette.jpg',
  'cream-moisturizing.jpg',
];

const svg = `
<svg width="1200" height="1200" viewBox="0 0 1200 1200" xmlns="http://www.w3.org/2000/svg">
  <defs>
    <linearGradient id="greigeGrad" x1="0%" y1="0%" x2="100%" y2="100%">
      <stop offset="0%" stop-color="#CFC8BE"/>
      <stop offset="100%" stop-color="#B9B1A6"/>
    </linearGradient>
    <filter id="shadow" x="-20%" y="-20%" width="140%" height="140%">
      <feDropShadow dx="0" dy="24" stdDeviation="32" flood-color="#000000" flood-opacity="0.14"/>
    </filter>
  </defs>
  <rect width="1200" height="1200" fill="url(#greigeGrad)"/>
  <rect x="420" y="300" width="360" height="600" rx="48" fill="#9E9589" filter="url(#shadow)"/>
</svg>
`;

async function generate() {
  console.log('[Media] Generating 6 temporary placeholder packshots...');
  for (const filename of productNames) {
    const dest = path.join(outputDir, filename);
    await sharp(Buffer.from(svg))
      .jpeg({ quality: 92 })
      .toFile(dest);
    console.log(`  -> Created ${filename} (1200x1200px)`);
  }

  // Create PLACEHOLDERS.md
  const markdownContent = `# Temporary Product Packshot Placeholders

These 6 files are TEMPORARY placeholders generated by sharp (1200x1200px, warm greige gradient #CFC8BE to #B9B1A6 with rounded silhouette):
- \`serum-vitamin-c.jpg\` (prod-1)
- \`cleanser-hydrating.jpg\` (prod-2)
- \`serum-niacinamide.jpg\` (prod-3)
- \`lipstick-couture.jpg\` (prod-4)
- \`eyeshadow-palette.jpg\` (prod-5)
- \`cream-moisturizing.jpg\` (prod-6)

## Action Required
Overwrite these files with real studio packshot photography (square, warm greige studio backdrop) as soon as external image generation quota is replenished.
`;

  fs.writeFileSync(path.join(outputDir, 'PLACEHOLDERS.md'), markdownContent, 'utf-8');
  console.log('[Media] Successfully generated placeholders and PLACEHOLDERS.md');
}

generate().catch(err => {
  console.error('[Media] Generation failed:', err);
  process.exit(1);
});
